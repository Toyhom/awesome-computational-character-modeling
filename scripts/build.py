"""Generate reading lists from independent category CSVs (Python 3.10+).

This script only READS catalog/*.csv. It never merges records between
categories or propagates one category's metadata to another.
"""
from __future__ import annotations

import argparse
import csv
import html
import io
import json
import re
import sys
from datetime import date
from pathlib import Path
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ['id','title','authors','year','venue','paper_url','doi','arxiv_id','code_url','data_url','note']
NOTICE = '<!-- Generated by scripts/build.py. Edit the linked category CSV or templates/README.md. -->\n'


def leaves(nodes):
    for node in nodes:
        if 'file' in node:
            yield node
        yield from leaves(node.get('children', []))


def safe_path(root, value):
    path = (root / value).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f'Path escapes repository: {value}')
    return path


def md(value):
    value = html.escape(str(value), quote=False).replace('\r',' ').replace('\n',' ')
    for ch in '\\`*[]_|':
        value = value.replace(ch, '\\' + ch)
    return value


def href(url):
    return quote(url, safe=':/?&=#%@+,-._~')


def load(root=ROOT):
    manifest=json.loads((root/'catalog/structure.json').read_text(encoding='utf-8'))
    categories=list(leaves(manifest['groups']))
    seen_nodes=set()
    def check_nodes(nodes):
        for n in nodes:
            if not re.fullmatch(r'[a-z0-9-]+',n['id']) or n['id'] in seen_nodes:
                raise ValueError(f'Invalid or repeated category ID: {n["id"]}')
            seen_nodes.add(n['id'])
            check_nodes(n.get('children',[]))
    check_nodes(manifest['groups'])
    files=set(); records={}
    for c in categories:
        path=safe_path(root,c['file'])
        if path in files: raise ValueError(f'Category files must be independent: {path}')
        files.add(path)
        with path.open(encoding='utf-8-sig',newline='') as f:
            reader=csv.DictReader(f)
            if reader.fieldnames!=FIELDS: raise ValueError(f'{c["file"]}: expected columns {FIELDS}')
            rows=list(reader)
        seen=set(); identifiers={'doi':set(),'arxiv_id':set()}
        for lineno,r in enumerate(rows,2):
            prefix=f'{c["file"]}:{lineno}'
            if None in r or any(v is None for v in r.values()): raise ValueError(f'{prefix}: malformed CSV row')
            if not re.fullmatch(r'[A-Za-z0-9_.:-]+',r['id']): raise ValueError(f'{prefix}: invalid id')
            if r['id'] in seen: raise ValueError(f'{prefix}: duplicate id inside this category: {r["id"]}')
            seen.add(r['id'])
            for field in ['title','authors','year','venue']:
                if not r[field].strip(): raise ValueError(f'{prefix}: missing {field}')
            if not re.fullmatch(r'\d{4}',r['year']) or not 1800<=int(r['year'])<=date.today().year+1:
                raise ValueError(f'{prefix}: invalid year')
            for field in ['paper_url','code_url','data_url']:
                if r[field]:
                    url=urlsplit(r[field])
                    if url.scheme not in {'https','http'} or not url.netloc or url.username or url.password or re.search(r'\s',r[field]):
                        raise ValueError(f'{prefix}: invalid {field}')
            for field in identifiers:
                value=r[field].lower().strip()
                if value:
                    if value in identifiers[field]: raise ValueError(f'{prefix}: duplicate {field} inside this category')
                    identifiers[field].add(value)
            if r['doi'] and not re.fullmatch(r'10\.\d{4,9}/\S+',r['doi']): raise ValueError(f'{prefix}: invalid DOI')
            if r['arxiv_id'] and not re.fullmatch(r'\d{4}\.\d{4,5}(v\d+)?',r['arxiv_id']): raise ValueError(f'{prefix}: invalid arXiv ID')
        records[c['id']]=sorted(rows,key=lambda r:(-int(r['year']),r['title'].casefold(),r['id']))
    actual={p.resolve() for p in (root/'catalog').rglob('*.csv')}
    if actual!=files: raise ValueError('Unlisted catalog CSV files: '+str(actual-files))
    return manifest,records


def links(r):
    result=[]
    for label,field in [('Paper','paper_url'),('Code','code_url'),('Data','data_url')]:
        if r[field]: result.append(f'[{label}]({href(r[field])})')
    if r['arxiv_id'] and 'arxiv.org' not in r['paper_url']:
        result.append(f'[arXiv](https://arxiv.org/abs/{r["arxiv_id"]})')
    return ' · '.join(result) or '—'


def table(rows):
    out=['| Year | Paper | Venue | Links |','| :-- | :-- | :-- | :-- |']
    for r in rows:
        out.append(f'| {r["year"]} | **{md(r["title"])}** | {md(r["venue"])} | {links(r)} |')
    return '\n'.join(out)+'\n'


def bibtex(rows):
    # A separate bibliography for each category preserves divergent local edits.
    def esc(s):
        return s.replace('\\',r'\textbackslash{}').replace('{',r'\{').replace('}',r'\}').replace('&',r'\&').replace('%',r'\%').replace('_',r'\_').replace('#',r'\#')
    out=[]
    for r in rows:
        fields={'title':esc(r['title']),'author':esc(r['authors'].replace('; ',' and ')),'year':r['year'],'howpublished':esc(r['venue'])}
        if r['paper_url']: fields['url']=r['paper_url']
        if r['doi']: fields['doi']=r['doi']
        if r['arxiv_id']: fields.update(eprint=r['arxiv_id'],archivePrefix='arXiv')
        out.append('@misc{'+r['id']+',\n'+',\n'.join('  '+k+' = {'+v+'}' for k,v in fields.items())+'\n}\n')
    return '\n'.join(out)


def generate(root=ROOT):
    manifest,records=load(root)
    outputs={}; all_rows=[]; counts=[]
    for g in manifest['groups']:
        group_rows=[r for c in leaves([g]) for r in records[c['id']]]
        counts.append((g,len({r['id'] for r in group_rows}),len(group_rows)))
    overview=['| Survey chapter | Browse |','| :-- | :-- |']
    for g,unique,n in counts: overview.append(f'| {g["section"]}. {g["title"]} | [{g["id"].title()}](#{g["id"]}) |')
    toc=[]
    def outline(nodes,depth=0):
        for c in nodes:
            toc.append('  '*depth+f'- [{md(c["title"])}](#{c["id"]})')
            outline(c.get('children',[]),depth+1)
    outline(manifest['groups'])
    body=[]
    def render_nodes(nodes,level=2):
        for c in nodes:
            body.extend([f'<a id="{c["id"]}"></a>',f'{"#"*min(level,6)} {c["title"]}',''])
            if 'file' in c:
                rows=records[c['id']]
                view=c['file'].replace('catalog/','literature/').removesuffix('.csv')+'.md'
                bib=view.removesuffix('.md')+'.bib'
                body.extend([f'Survey §{c["section"]} · [Edit this category]({c["file"]}) · [Detailed list]({view}) · [BibTeX]({bib})',''])
                if c.get('description'): body.extend([c['description'],''])
                if rows:
                    body.extend([f'<details open><summary>{len(rows)} references · newest first</summary>','',table(rows),'</details>',''])
                detail=[NOTICE,f'# {c["title"]}','',f'Survey §{c["section"]} · [Back to README](../../README.md#{c["id"]}) · [Edit category](../../{c["file"]}) · [BibTeX]({Path(bib).name})','']
                if c.get('description'):detail.extend([c['description'],''])
                for r in rows:
                    detail.extend([f'<a id="{r["id"]}"></a>',f'## {md(r["title"])}','',f'{md(r["authors"])}','',f'**{r["year"]} · {md(r["venue"])}** · {links(r)}',''])
                    if r['note']:detail.extend([md(r['note']),''])
                    all_rows.append({'category':c['id'],**r})
                outputs[view]='\n'.join(detail).rstrip()+'\n'
                outputs[bib]=bibtex(rows)
            render_nodes(c.get('children',[]),level+1)
    render_nodes(manifest['groups'])
    template=(root/'templates/README.md').read_text(encoding='utf-8')
    unique=len({r['id'] for r in all_rows})
    values={'title':manifest['name'],'survey_title':manifest['survey_title'],'unique':str(unique),'records':str(len(all_rows)),'categories':str(len(records)),'overview':'\n'.join(overview),'toc':'\n'.join(toc),'catalog':'\n'.join(body)}
    for key,value in values.items():template=template.replace('{{'+key+'}}',value)
    if re.search(r'\{\{\w+\}\}',template):raise ValueError('Unknown template token')
    outputs['README.md']=NOTICE+template
    index=[NOTICE,'# Literature directory','', 'Browse references by survey chapter and subsection.','', '| Section | Category | Edit metadata | Read | Export |','| :-- | :-- | :-- | :-- | :-- |']
    for c in leaves(manifest['groups']):
        view=c['file'].replace('catalog/','literature/').removesuffix('.csv')
        index.append(f'| {c["section"]} | {c["title"]} | [CSV](../{c["file"]}) | [List](../{view}.md) | [BibTeX](../{view}.bib) |')
    outputs['literature/README.md']='\n'.join(index)+'\n'
    buff=io.StringIO(newline='');w=csv.DictWriter(buff,fieldnames=['category']+FIELDS,lineterminator='\n');w.writeheader();w.writerows(all_rows)
    outputs['exports/catalog.csv']=buff.getvalue()
    outputs['exports/stats.json']=json.dumps(dict(unique_citation_ids=unique,category_records=len(all_rows),category_files=len(records),chapters={g['id']:{'unique_citation_ids':u,'records':n} for g,u,n in counts}),ensure_ascii=False,indent=2)+'\n'
    return outputs


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Report stale generated files; write nothing')
    args=parser.parse_args()
    try:
        outputs=generate()
        stale=[]
        for rel,text in outputs.items():
            path=ROOT/rel
            if not path.exists() or path.read_text(encoding='utf-8')!=text:
                stale.append(rel)
                if not args.check:
                    path.parent.mkdir(parents=True,exist_ok=True)
                    path.write_text(text,encoding='utf-8',newline='\n')
        obsolete=[p for p in (ROOT/'literature').rglob('*') if p.is_file() and p.suffix in {'.md','.bib'} and p.relative_to(ROOT).as_posix() not in outputs]
        if obsolete:
            raise ValueError('Remove retired generated files explicitly: '+', '.join(str(p.relative_to(ROOT)) for p in obsolete))
        if args.check and stale:
            print('Generated files need updating. Run: python scripts/build.py\n'+'\n'.join(stale));return 1
        print(f'Validated independent categories; {len(outputs)} generated files; {len(stale)} '+('stale.' if args.check else 'updated.'))
        return 0
    except (ValueError,KeyError,OSError,json.JSONDecodeError) as e:
        print(f'Catalog error: {e}',file=sys.stderr);return 1


if __name__=='__main__':
    raise SystemExit(main())
